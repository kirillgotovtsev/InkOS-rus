export interface MessageTemplate {
  readonly template: string;
  readonly values: readonly unknown[];
}

/** Runtime values remain opaque: filenames and user text are never parsed. */
export function messageTemplate(template: string, ...values: readonly unknown[]): MessageTemplate {
  return { template, values };
}

/** Translate built-in copy only. Unknown diagnostics pass through unchanged. */
export function translateRussian(message: string): string {
  return Object.hasOwn(RUSSIAN_MESSAGES, message) ? RUSSIAN_MESSAGES[message]! : message;
}

export function renderLocalizedMessage(message: string | MessageTemplate, language: "en" | "ru"): string {
  if (typeof message === "string") return language === "ru" ? translateRussian(message) : message;
  const template = language === "ru" ? translateRussian(message.template) : message.template;
  return template.replace(/\{\{(\d+)\}\}/g, (token, index: string) => {
    const position = Number(index);
    return position < message.values.length ? String(message.values[position]) : token;
  });
}

export function formatRussian(template: string | MessageTemplate, ...values: readonly unknown[]): string {
  return renderLocalizedMessage(typeof template === "string" ? messageTemplate(template, ...values) : template, "ru");
}
